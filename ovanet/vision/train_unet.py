"""
ovanet/vision/train_unet.py

Training script for weakly-supervised U-Net segmentation.
Trains on pseudo-masks generated by classical detector (Day 4).

Features:
  - Architecture: smp.Unet (resnet18 encoder, 2 output channels)
  - Loss: Combined BCEWithLogitsLoss + DiceLoss
  - Metrics: Ovary Dice, Follicle Dice
  - Checkpointing: Saves weights/unet_resnet18_best.pth (<50MB)
"""

import argparse
from pathlib import Path
import numpy as np
import pandas as pd
import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from tqdm import tqdm

import segmentation_models_pytorch as smp
from ovanet.vision.unet import OvaNetUNet
from ovanet.vision.dataset import OvaNetSegmentationDataset


def dice_score(preds: torch.Tensor, targets: torch.Tensor, smooth: float = 1e-6) -> float:
    """Compute soft Dice coefficient for binary predictions [0, 1]."""
    preds = preds.contiguous().view(-1)
    targets = targets.contiguous().view(-1)
    intersection = (preds * targets).sum()
    return float((2.0 * intersection + smooth) / (preds.sum() + targets.sum() + smooth))


class CombinedBCEDiceLoss(nn.Module):
    """Combined BCE with Logits and Dice Loss for 2-channel segmentation."""

    def __init__(self, bce_weight: float = 0.5, dice_weight: float = 0.5):
        super().__init__()
        self.bce_weight = bce_weight
        self.dice_weight = dice_weight
        self.bce = nn.BCEWithLogitsLoss()
        self.dice = smp.losses.DiceLoss(mode="multilabel", from_logits=True)

    def forward(self, logits: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        loss_bce = self.bce(logits, targets)
        loss_dice = self.dice(logits, targets)
        return self.bce_weight * loss_bce + self.dice_weight * loss_dice


def train_one_epoch(
    model: nn.Module,
    loader: DataLoader,
    optimizer: torch.optim.Optimizer,
    criterion: nn.Module,
    device: torch.device,
) -> tuple[float, float, float]:
    model.train()
    total_loss = 0.0
    ovary_dices = []
    follicle_dices = []

    for batch in tqdm(loader, desc="Training", leave=False):
        images = batch["image"].to(device)
        masks = batch["mask"].to(device)

        optimizer.zero_grad()
        logits = model(images)
        loss = criterion(logits, masks)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

        # Compute batch metrics
        probs = torch.sigmoid(logits)
        preds = (probs >= 0.5).float()
        ovary_dices.append(dice_score(preds[:, 0], masks[:, 0]))
        follicle_dices.append(dice_score(preds[:, 1], masks[:, 1]))

    mean_loss = total_loss / max(1, len(loader))
    return mean_loss, float(np.mean(ovary_dices)), float(np.mean(follicle_dices))


@torch.no_grad()
def evaluate(
    model: nn.Module,
    loader: DataLoader,
    criterion: nn.Module,
    device: torch.device,
) -> tuple[float, float, float]:
    model.eval()
    total_loss = 0.0
    ovary_dices = []
    follicle_dices = []

    for batch in tqdm(loader, desc="Validating", leave=False):
        images = batch["image"].to(device)
        masks = batch["mask"].to(device)

        logits = model(images)
        loss = criterion(logits, masks)
        total_loss += loss.item()

        probs = torch.sigmoid(logits)
        preds = (probs >= 0.5).float()
        ovary_dices.append(dice_score(preds[:, 0], masks[:, 0]))
        follicle_dices.append(dice_score(preds[:, 1], masks[:, 1]))

    mean_loss = total_loss / max(1, len(loader))
    return mean_loss, float(np.mean(ovary_dices)), float(np.mean(follicle_dices))


def run_training(
    manifest_train: Path,
    manifest_val: Path,
    raw_root: Path,
    mask_dir: Path,
    output_weights: Path,
    epochs: int = 15,
    batch_size: int = 16,
    lr: float = 3e-4,
    device_name: str | None = None,
):
    device = torch.device(device_name if device_name else ("cuda" if torch.cuda.is_available() else "cpu"))
    print(f"=== Starting U-Net Training on device={device} ===")

    train_df = pd.read_csv(manifest_train)
    val_df = pd.read_csv(manifest_val)

    train_dataset = OvaNetSegmentationDataset(train_df, raw_root=raw_root, mask_dir=mask_dir, is_train=True)
    val_dataset = OvaNetSegmentationDataset(val_df, raw_root=raw_root, mask_dir=mask_dir, is_train=False)

    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True, num_workers=2, pin_memory=True)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False, num_workers=2)

    model = OvaNetUNet(encoder_name="resnet18", encoder_weights="imagenet", in_channels=1, classes=2).to(device)
    criterion = CombinedBCEDiceLoss(bce_weight=0.5, dice_weight=0.5)
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)

    best_val_dice = 0.0

    for epoch in range(1, epochs + 1):
        train_loss, train_ovary_dice, train_follicle_dice = train_one_epoch(model, train_loader, optimizer, criterion, device)
        val_loss, val_ovary_dice, val_follicle_dice = evaluate(model, val_loader, criterion, device)
        scheduler.step()

        val_mean_dice = (val_ovary_dice + val_follicle_dice) / 2.0
        print(
            f"Epoch [{epoch:02d}/{epochs:02d}] "
            f"Train Loss: {train_loss:.4f} | Ovary Dice: {train_ovary_dice:.3f} | Follicle Dice: {train_follicle_dice:.3f} | "
            f"Val Loss: {val_loss:.4f} | Val Ovary: {val_ovary_dice:.3f} | Val Follicle: {val_follicle_dice:.3f}"
        )

        if val_mean_dice > best_val_dice:
            best_val_dice = val_mean_dice
            print(f"  --> Saving new best model checkpoint (Val Mean Dice: {best_val_dice:.4f}) to {output_weights}")
            model.save_checkpoint(
                output_weights,
                epoch=epoch,
                metrics={
                    "val_loss": val_loss,
                    "val_ovary_dice": val_ovary_dice,
                    "val_follicle_dice": val_follicle_dice,
                    "val_mean_dice": val_mean_dice,
                },
            )

    print(f"\nTraining Complete! Best Val Mean Dice: {best_val_dice:.4f}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest-train", default="data/pseudo_masks/manifest_train.csv")
    parser.add_argument("--manifest-val", default="data/pseudo_masks/manifest_val.csv")
    parser.add_argument("--raw-root", default="data/raw/pcos_primary/data")
    parser.add_argument("--mask-dir", default="data/pseudo_masks")
    parser.add_argument("--output-weights", default="weights/unet_resnet18_best.pth")
    parser.add_argument("--epochs", type=int, default=15)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--lr", type=float, default=3e-4)
    parser.add_argument("--device", default=None)
    args = parser.parse_args()

    run_training(
        manifest_train=Path(args.manifest_train),
        manifest_val=Path(args.manifest_val),
        raw_root=Path(args.raw_root),
        mask_dir=Path(args.mask_dir),
        output_weights=Path(args.output_weights),
        epochs=args.epochs,
        batch_size=args.batch_size,
        lr=args.lr,
        device_name=args.device,
    )
